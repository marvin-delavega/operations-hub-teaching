# ============================================================================
#  install-app-deps.ps1
#  Install-time dependency bootstrap for the Operations Hub installer.
#  Runs once at install (from installer/OperationsHub.iss [Run]) on the TARGET.
#
#  What it does:
#    1. npm ci -- pins deps to package-lock.json (no node_modules shipped).
#    2. Ensures a .env.local exists with an AUTH_SECRET (never shipped from the
#       dev machine). If one already exists it is left untouched.
#    3. npm run build -- production build on the target.
#
#  Idempotent: on a swap-in-place reinstall with an up-to-date .next it still
#  re-runs npm ci (cheap/fast) but you may add a skip-build guard if desired.
# ============================================================================
param()

$ErrorActionPreference = "Stop"

# Script sits in <install>\scripts; the app root is its parent.
$appRoot = Resolve-Path "$PSScriptRoot\.."
Set-Location $appRoot

Write-Host "==> npm ci (installing pinned dependencies)..." -ForegroundColor Cyan
npm ci --no-audit --no-fund
if ($LASTEXITCODE -ne 0) { throw "npm ci failed (exit $LASTEXITCODE). Is Node/npm installed and is the registry reachable?" }

# --- Ensure .env.local exists with an AUTH_SECRET, without clobbering ------
$envFile = Join-Path $appRoot ".env.local"
if (-not (Test-Path $envFile)) {
    Write-Host "==> No .env.local found; generating one with a fresh AUTH_SECRET..." -ForegroundColor Cyan
    # 32 random bytes -> 64 hex chars (>= Auth.js' 32-char minimum).
    $secret = & node -e "console.log(require('crypto').randomBytes(32).toString('hex'))"
    if (-not $secret) { throw "Could not generate an AUTH_SECRET via node." }
    $content = @"
# Generated by the Operations Hub installer. Replace ROLLUP_REFRESH_TOKEN with a
# shared secret for the nightly rollup refresh endpoint before enabling that task.
AUTH_SECRET=$secret
ROLLUP_REFRESH_TOKEN=CHANGE_ME

# Optional: DB_* env vars act only as a seed/fallback. The real ActiveOne
# connection is configured from the UI (/connect) and stored in data/db-config.json.
# DB_HOST=
# DB_PORT=3306
# DB_USER=
# DB_PASSWORD=
# DB_NAME=
"@
    Set-Content -Path $envFile -Value $content -Encoding utf8
} else {
    Write-Host "==> .env.local exists; leaving it untouched." -ForegroundColor Yellow
}

# --- Production build ------------------------------------------------------
Write-Host "==> npm run build (production build on this machine)..." -ForegroundColor Cyan
npm run build
if ($LASTEXITCODE -ne 0) { throw "npm run build failed (exit $LASTEXITCODE)." }

Write-Host "==> Install-time setup complete." -ForegroundColor Green
